def addition_numbers(num1,num2):
  return num1 + num2


def subtraction_numbers(num1,num2):
  return num1 - num2


def multiplying_numbers(num1,num2):
  return num1 * num2

def dividing_numbers(num1,num2):
  return num1 / num2

print("Choose operation:")
print("1 - Addition")
print("2 - Subtraction")
print("3 - Multiplication")
print("4 - Division")

choice = input("Enter choice:")

num1 = float(input("Enter first number:"))
num2 = float(input("Enter second number:"))

if choice == '1':
   result = addition_numbers(num1,num2)
   print(f"Result: {result}")

elif choice == '2':
   result = subtraction_numbers(num1,num2)
   print(f"Result: {result}")

elif choice == '3':
   result = multiplying_numbers(num1,num2)
   print(f"Result: {result}")

elif choice == '4':
   result = dividing_numbers(num1,num2)

   print(f"Result: {result}")

else:
   print("Inavlid operation choice.")