#Addition - this function allows user to select the mathematical operation addition.
def add_numbers(num1,num2):
  return num1 + num2

#Subtraction - this function allows user to select the mathematical operation subtraction.
def minus_numbers(num1,num2): #"minus" is used instead of subtract for shorter layout format.
  return num1 - num2

#Multiplication - this function allows user to select the mathematical operation multiplication.
def x_numbers(num1,num2): #"x" is used instead of multiply for shorter layout format.
  return num1 * num2

#Division - this function allows user to select the mathematical operation division.
def divide_numbers(num1,num2):
  if num2 == 0: #If second number is zero, it displays "Cannot divide by zero." instead of error to keep the program working.
    return "Cannot divide by zero."
  return num1 / num2

print("Choose operation:") #This part allows the user to choose between 4 mathematical operations.
print("1 - Addition")
print("2 - Subtraction")
print("3 - Multiplication")
print("4 - Division")

choice = input("Enter choice:")

num1 = float(input("Enter first number:"))
num2 = float(input("Enter second number:"))

if choice == '1':
   result = add_numbers(num1,num2)
   print(f"Result: {result}")

elif choice == '2':
   result = minus_numbers(num1,num2)
   print(f"Result: {result}")

elif choice == '3':
   result = x_numbers(num1,num2)
   print(f"Result: {result}")

elif choice == '4':
   result = divide_numbers(num1,num2)

   print(f"Result: {result}")

else:
   print("Inavlid operation choice.") #Only outputs when user initiates an invalid option such as "5".


